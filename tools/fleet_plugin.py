"""Turn optimizer designs into an Endless Sky plugin that adds a test fleet to your current save.

    python tools/fleet_plugin.py --name "Late mid test fleet" --out aside/fleets/late-mid \\
        3:"KIV Warship":designs/kiv-warship.txt 2:"KIV Disabler":designs/kiv-disabler.txt ...

Each entry is COUNT:SHIP NAME:DESIGN, where DESIGN is the saved output of `es-optimizer optimize`. The plugin
defines one ship variant per design (the hull with exactly those outfits) and a one-time mission: the next time
you land anywhere, it offers to add the ships to your fleet. "Not now" brings the offer back on a later landing.

Install by copying the output folder into your plugins folder (~/.local/share/endless-sky/plugins/) and
restarting the game. Remove the folder afterwards; the ships stay yours.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

HEADER = re.compile(r"^(.+?) \([^()]*\) for .+: optimized")
OUTFIT = re.compile(r"^\s+(\d+) × (.+?)  \[[^\]]*\]$")


def parse_design(path: Path) -> tuple[str, dict[str, int]]:
    """(hull, outfits) from saved optimizer output."""
    hull, outfits = None, {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if hull is None and (m := HEADER.match(line)):
            hull = m.group(1)
        elif line.strip().startswith("Left:") or line.strip().startswith("Balance:"):
            break
        elif hull and (m := OUTFIT.match(line)):
            outfits[m.group(2)] = outfits.get(m.group(2), 0) + int(m.group(1))
    if not hull or not outfits:
        raise SystemExit(f"{path}: no optimized design found")
    return hull, outfits


def quote(text: str) -> str:
    """A data-file token: backquotes if it contains a double quote, else double quotes."""
    return f"`{text}`" if '"' in text else f'"{text}"'


def plugin(name: str, entries: list[tuple[int, str, str, dict[str, int]]]) -> str:
    slug = re.sub(r"[^a-z0-9]+", " ", name.lower()).strip()
    lines = [f"# {name}: generated by tools/fleet_plugin.py (es-optimizer). Not part of the game.", ""]
    for _, label, hull, outfits in entries:
        lines += [f"ship {quote(hull)} {quote(f'{label} ({slug})')}", "\toutfits"]
        lines += [f"\t\t{quote(o)}" + (f" {n}" if n > 1 else "") for o, n in sorted(outfits.items())]
        lines.append("")
    total = sum(count for count, *_ in entries)
    roster = ", ".join(f"{count} × {label}" for count, label, *_ in entries)
    lines += [
        f"mission {quote(f'es-optimizer: {name}')}",
        "\tinvisible",
        "\tlanding",
        "\ton offer",
        "\t\tconversation",
        f"\t\t\t`The test fleet \"{name}\" is waiting at the spaceport: {roster} ({total} ships). "
        "Crew and salaries are yours from now on.`",
        "\t\t\tchoice",
        "\t\t\t\t`\t(Take the ships.)`",
        "\t\t\t\t\tgoto take",
        "\t\t\t\t`\t(Not now.)`",
        "\t\t\t\t\tdefer",
        "\t\t\tlabel take",
        "\t\t\taction",
    ]
    for count, label, hull, _ in entries:
        for i in range(1, count + 1):
            lines.append(f"\t\t\t\tgive ship {quote(f'{label} ({slug})')} {quote(f'{label} {i}')}")
    lines += ["\t\t\tdecline", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--name", required=True, help="fleet name, shown in game")
    parser.add_argument("--out", required=True, help="plugin folder to write")
    parser.add_argument("entries", nargs="+", metavar="COUNT:SHIP NAME:DESIGN")
    args = parser.parse_args(argv)
    entries = []
    for item in args.entries:
        count, label, path = item.split(":", 2)
        hull, outfits = parse_design(Path(path))
        entries.append((int(count), label, hull, outfits))
    out = Path(args.out)
    (out / "data").mkdir(parents=True, exist_ok=True)
    (out / "data" / "fleet.txt").write_text(plugin(args.name, entries), encoding="utf-8")
    print(f"plugin written to {out}/ ({sum(e[0] for e in entries)} ships)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
